(() => {
  'use strict';
  // Application title follows the explicit URL, keeping each shared version independent.
  const roleKey=new URLSearchParams(location.search).get('role')==='uiux'?'uiux':'design-lead';
  const roleTitle=roleKey==='uiux'?'UI/UX Designer':'Design Lead';
  document.querySelectorAll('.site-role,.identity [data-copy="subtitle"],.resume-position,[data-profile-role]').forEach(el=>{el.textContent=roleTitle;});
  document.querySelectorAll('a[href]').forEach(link=>{
    const url=new URL(link.getAttribute('href'),location.href);
    if(url.origin===location.origin && /\.html$/.test(url.pathname) && !link.hasAttribute('download')){url.searchParams.set('role',roleKey);link.href=url.pathname+url.search+url.hash;}
  });

  document.querySelectorAll('.unified-nav').forEach(nav=>{nav.querySelectorAll('.nav-resume').forEach(link=>link.remove());const about=nav.querySelector('.nav-about');if(about)about.href='about.html?role='+roleKey;});
  document.querySelectorAll('.vd-canvas,.moon-type-guide,.component-demo').forEach(el=>el.setAttribute('data-ui',''));
  // Chapter IDs are generated by the original scripts before this presentation-only pass.
  document.querySelectorAll('.portfolio-case *').forEach(el=>{
    if(el.children.length || el.closest('[data-ui],script,style,pre,code') || el.namespaceURI!=='http://www.w3.org/1999/xhtml') return;
    el.textContent=el.textContent.replace(/^\s*0[1-9]\s*[\/·]\s*/,'').replace(/^\s*0[1-9]\s*$/,'').replace(/\s*[·/]\s*\d+\s*\/\s*\d+\s*$/,'');
  });
  document.querySelectorAll('.visual-draft>header>span').forEach(el=>{el.textContent=el.textContent.replace('DESIGN EXPLAINED','Design explained');});
  document.querySelectorAll('.next-case').forEach(section=>{
    section.setAttribute('aria-label','Next project');
    const link=section.querySelector('a');
    if(link) link.setAttribute('aria-label','Next project: '+link.textContent.trim());
  });

  const main=document.querySelector('main');
  if(main){
    if(!main.id)main.id='main-content';
    main.tabIndex=-1;
    if(!document.querySelector('.skip-link,.resume-skip')){
      const skip=document.createElement('a');skip.className='site-skip';skip.href='#'+main.id;skip.textContent=new URLSearchParams(location.search).get('lang')==='ja'?'本文へスキップ':'Skip to main content';document.body.prepend(skip);
      skip.addEventListener('click',()=>main.focus({preventScroll:true}));
    }
  }
  const wall=document.querySelector('.advisor-brand-showcase');
  if(wall){const button=document.createElement('button');button.className='site-motion-toggle';button.type='button';button.textContent='Pause animation';button.setAttribute('aria-pressed','false');wall.after(button);button.addEventListener('click',()=>{const paused=document.body.classList.toggle('site-motion-paused');button.setAttribute('aria-pressed',String(paused));button.textContent=paused?'Play animation':'Pause animation';});}
})();
